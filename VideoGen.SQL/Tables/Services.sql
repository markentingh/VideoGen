CREATE TABLE IF NOT EXISTS public."Services" (
    "Id" SERIAL PRIMARY KEY,
    "Key" VARCHAR(100) NOT NULL UNIQUE,
    "Version" VARCHAR(50) NOT NULL,
    "Name" VARCHAR(255) NOT NULL,
    "Type" INTEGER NOT NULL,
    "GitRepo" VARCHAR(1000) NOT NULL,
    "Installed" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "InstalledFiles" TEXT NOT NULL DEFAULT '',
    "HasSchema" BOOLEAN NOT NULL DEFAULT FALSE
);

ALTER TABLE public."Services" DROP COLUMN IF EXISTS "Icon";
ALTER TABLE public."Services" ADD COLUMN IF NOT EXISTS "HasSchema" BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public."Services" ADD COLUMN IF NOT EXISTS "InstalledFiles" TEXT NOT NULL DEFAULT '';
